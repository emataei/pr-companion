/**
 * PR Comment Script for Code Change Heat Map
 * Posts the PR code change heat map as a separate comment
 */

const fs = require('fs');
const path = require('path');

module.exports = async ({ github, context }) => {
  try {
    console.log('Starting code change heat map PR comment...');
    
    // Load heat map metadata
    const metadataPath = path.join('.code-analysis/outputs/heatmap_metadata.json');
    
    if (!fs.existsSync(metadataPath)) {
      console.log('No heat map metadata found, skipping comment');
      return {
        success: false,
        message: 'Heat map metadata not available'
      };
    }
    
    const metadataContent = fs.readFileSync(metadataPath, 'utf8');
    const metadata = JSON.parse(metadataContent);
    console.log('Loaded heat map metadata:', metadata);
    
    // Check if there are any file changes
    if (metadata.total_files === 0 || metadata.error) {
      console.log('No file changes detected, skipping heat map comment');
      return {
        success: false,
        message: 'No file changes to display in heat map'
      };
    }
    
    // Construct GitHub Pages URL for the heat map
    const owner = context.repo.owner;
    const repo = context.repo.repo;
    const prNumber = context.issue.number;
    const baseUrl = `https://${owner}.github.io/${repo}`;
    const heatmapUrl = `${baseUrl}/pr/${prNumber}/code_change_heatmap.png`;
    
    // Create cache busting parameters
    const timestamp = Date.now();
    const randomId = Math.floor(Math.random() * 10000);
    const runNumber = process.env.GITHUB_RUN_NUMBER || timestamp;
    const heatmapUrlWithCache = `${heatmapUrl}?_cb=${timestamp}&_r=${randomId}&_run=${runNumber}`;
    
    // Format file types for display
    const fileTypesText = Object.entries(metadata.file_types || {})
      .sort((a, b) => b[1] - a[1])
      .slice(0, 5)
      .map(([type, count]) => `${type || 'no extension'} (${count})`)
      .join(', ');
    
    // Create the comment body
    const commentBody = `## 🗺️ PR Code Change Heat Map

This heat map visualizes all code changes in this PR, with color intensity indicating the magnitude of changes.

### 📊 Change Summary
- **Total Files Changed:** ${metadata.total_files}
- **Total Lines Added:** +${metadata.total_additions}
- **Total Lines Deleted:** -${metadata.total_deletions}
- **Net Change:** ${metadata.total_additions - metadata.total_deletions >= 0 ? '+' : ''}${metadata.total_additions - metadata.total_deletions} lines
${metadata.most_changed_file ? `\n**Most Changed File:** \`${metadata.most_changed_file.file}\` (+${metadata.most_changed_file.additions} -${metadata.most_changed_file.deletions})` : ''}

**Top File Types:** ${fileTypesText}

### 🎨 Heat Map Legend
- 🟢 **Green** = More additions than deletions (new code)
- 🔴 **Red** = More deletions than additions (code removal)
- 🔵 **Blue** = Balanced changes (refactoring)
- **Color Intensity** = Magnitude of changes (darker = more changes)

> **Note**: If the image appears broken initially, GitHub Pages may still be deploying. Please wait a few minutes and refresh.

![Code Change Heat Map](${heatmapUrlWithCache})

---

*[View full-size heat map](${heatmapUrl})*

---
*Generated by PR Companion - Code Change Heat Map*
<!-- PR_HEATMAP_COMMENT -->`;

    // Find existing heat map comment
    const comments = await github.rest.issues.listComments({
      owner: context.repo.owner,
      repo: context.repo.repo,
      issue_number: context.issue.number,
    });

    const existingComment = comments.data.find(comment => 
      comment.body.includes('<!-- PR_HEATMAP_COMMENT -->') ||
      comment.body.includes('PR Code Change Heat Map') ||
      comment.body.includes('🗺️ PR Code Change Heat Map')
    );

    if (existingComment) {
      // Update existing comment
      console.log(`Updating existing heat map comment (ID: ${existingComment.id})...`);
      try {
        await github.rest.issues.updateComment({
          owner: context.repo.owner,
          repo: context.repo.repo,
          comment_id: existingComment.id,
          body: commentBody
        });
        console.log('Successfully updated existing heat map comment');
      } catch (updateError) {
        console.error('Failed to update existing comment:', updateError);
        // If update fails, create a new comment
        const comment = await github.rest.issues.createComment({
          owner: context.repo.owner,
          repo: context.repo.repo,
          issue_number: context.issue.number,
          body: commentBody
        });
        console.log('Created new heat map comment with ID:', comment.data.id);
      }
    } else {
      // Create new comment
      console.log('Creating new heat map comment...');
      const comment = await github.rest.issues.createComment({
        owner: context.repo.owner,
        repo: context.repo.repo,
        issue_number: context.issue.number,
        body: commentBody
      });
      console.log('Created new heat map comment with ID:', comment.data.id);
    }

    return {
      success: true,
      message: 'Heat map comment posted successfully',
      metadata: metadata
    };

  } catch (error) {
    console.error('Error in heat map PR comment:', error);
    
    // Create a fallback comment
    const fallbackBody = `## 🗺️ PR Code Change Heat Map

Heat map generation is in progress...

This comment will be updated once the heat map is available on GitHub Pages.

**If this is the first PR:**
1. GitHub Pages may need to be enabled in repository settings
2. Go to Settings → Pages → Deploy from gh-pages branch
3. Wait 5-10 minutes for initial deployment

---
*Generated by PR Companion - Code Change Heat Map*
<!-- PR_HEATMAP_COMMENT -->`;

    try {
      // Try to create fallback comment
      await github.rest.issues.createComment({
        owner: context.repo.owner,
        repo: context.repo.repo,
        issue_number: context.issue.number,
        body: fallbackBody
      });
      console.log('Created fallback heat map comment');
    } catch (fallbackError) {
      console.error('Failed to create fallback comment:', fallbackError);
    }

    throw error;
  }
};
